"""
Group report aggregation helper for single compiled outbound delivery.

This module buffers per-image rule outputs under a group id and compiles one
final user-facing report using an LLM when the expected number of items arrives.
"""

from __future__ import annotations

import json
import os
import time
from dataclasses import dataclass
from typing import Any, Optional

import redis
from dotenv import load_dotenv
from langchain.agents import create_agent
from langchain_core.runnables import RunnableConfig
from langchain_openai import ChatOpenAI
from pydantic import BaseModel

from dermascan.shared.concise_report_format import (
    MicroReportFields,
    dermatologist_connection_guidance,
    micro_report_format_instructions,
    render_micro_report,
)
from dermascan.shared.logger import get_logger
from dermascan.shared.langsmith_observability import (
    build_invoke_config,
    configure_worker_project,
)

load_dotenv()
configure_worker_project("reports")

logger = get_logger(__name__)

REDIS_URL: str = os.getenv("REDIS_URL", "")
OPENAI_API_KEY: str = os.getenv("OPENAI_API_KEY_QUTIS", "")
GROUP_REPORT_MODEL: str = os.getenv("GROUP_REPORT_MODEL", "gpt-4o")
GROUP_REPORT_TTL_S: int = int(os.getenv("GROUP_REPORT_TTL_S", "86400"))

_redis: redis.Redis | None = redis.Redis.from_url(REDIS_URL, decode_responses=True) if REDIS_URL else None


class CompiledGroupReport(MicroReportFields):
    """Structured final text generated by the group report compiler."""


@dataclass(frozen=True)
class GroupAggregationResult:
    """Result of attempting to aggregate one group item."""

    should_send: bool
    compiled_text: str = ""
    reason: str = ""


def _group_meta_key(group_id: str) -> str:
    return f"group_report:{group_id}:meta"


def _group_items_key(group_id: str) -> str:
    return f"group_report:{group_id}:items"


def _group_sent_key(group_id: str) -> str:
    return f"group_report:{group_id}:sent"


def _safe_int(value: Any, default: int = 0) -> int:
    try:
        return int(str(value))
    except Exception:
        return default


def _build_compiler_agent() -> Any:
    model = ChatOpenAI(
        model=GROUP_REPORT_MODEL,
        api_key=OPENAI_API_KEY,
        temperature=0,
    )
    return create_agent(
        model=model,
        tools=[],
        response_format=CompiledGroupReport,
        system_prompt=(
            "You compile dermatology review outputs from multiple images into one concise user reply. "
            "Preserve all critical safety signals and avoid contradictions. "
            "Use simple, clear language for non-technical users. "
            f"{micro_report_format_instructions()} "
            f"{dermatologist_connection_guidance()} "
            "Output plain text only. No markdown."
        ),
    )


def _compile_group_report(
    *,
    group_id: str,
    signal_type: str,
    request_id: str,
    entries: list[dict[str, Any]],
    fallback_text: str,
    delivery_context_prompt: str = "",
) -> str:
    if not entries:
        return fallback_text
    if not OPENAI_API_KEY:
        return fallback_text

    agent = _build_compiler_agent()
    prompt = (
        "Compile one final outbound message for this grouped-image review.\n"
        "Requirements:\n"
        "- Mention each image item briefly in the bullets or headline.\n"
        "- Keep safety guidance explicit and practical.\n"
        "- Avoid duplications and contradictions.\n"
        f"{micro_report_format_instructions()}\n"
        "- Always include the sources of the information at the end of the report. Sources should be a list of URLs not exceeding 3."
        "- Output plain text only.\n"
        "- Personalize using client profile and intake context when provided.\n"
        f"group_id: {group_id}\n"
        f"signal_type: {signal_type}\n"
        f"items_json: {json.dumps(entries, default=str)}\n"
    )
    if delivery_context_prompt:
        prompt = f"{prompt}\nclient_context_for_personalization:\n{delivery_context_prompt}\n"
    try:
        config: RunnableConfig = build_invoke_config(
            thread_id=group_id,
            checkpoint_ns="group_report",
            run_name=f"group_report:{signal_type}",
            flow="signal",
            request_id=request_id,
            extra_metadata={
                "group_id": group_id,
                "signal_type": signal_type,
                "item_count": len(entries),
            },
            extra_tags=["group_report", signal_type] if signal_type else ["group_report"],
        )
        response = agent.invoke(
            {"messages": [{"role": "user", "content": prompt}]},
            config=config,
        )
        structured = response.get("structured_response") if isinstance(response, dict) else None
        if isinstance(structured, CompiledGroupReport) and structured.headline.strip():
            text = render_micro_report(structured)
            if text:
                return text
    except Exception:
        logger.exception("group report compile failed: group_id=%s", group_id)

    return fallback_text


def collect_and_compile_if_ready(
    *,
    group_id: str,
    expected_count: int,
    request_id: str,
    signal_type: str,
    item_text: str,
    item_payload: dict[str, Any],
    delivery_context_prompt: str = "",
) -> GroupAggregationResult:
    """
    Add one group item and compile final report when all items are available.

    Args:
        group_id: Shared group identifier across sibling image jobs.
        expected_count: Number of images/items expected in group.
        request_id: Request id for this item (used as item key).
        signal_type: Signal type for context.
        item_text: Item-level user-facing text.
        item_payload: Raw item result payload for compiler context.

    Returns:
        GroupAggregationResult indicating whether caller should send outbound now.
    """
    if _redis is None:
        return GroupAggregationResult(should_send=True, compiled_text=item_text, reason="redis_unavailable")
    gid = str(group_id or "").strip()
    if not gid:
        return GroupAggregationResult(should_send=True, compiled_text=item_text, reason="missing_group_id")

    expected = max(1, expected_count)
    now_ms = int(time.time() * 1000)

    try:
        meta_key = _group_meta_key(gid)
        items_key = _group_items_key(gid)
        sent_key = _group_sent_key(gid)

        # Store item atomically and refresh TTL.
        entry = {
            "request_id": request_id,
            "signal_type": signal_type,
            "item_text": item_text,
            "item_payload": item_payload,
            "ts_ms": now_ms,
        }
        pipe = _redis.pipeline()
        pipe.hset(meta_key, mapping={"expected_count": str(expected), "updated_at_ms": str(now_ms)})
        pipe.expire(meta_key, GROUP_REPORT_TTL_S)
        pipe.hset(items_key, request_id, json.dumps(entry, default=str))
        pipe.expire(items_key, GROUP_REPORT_TTL_S)
        pipe.execute()

        raw_items = _redis.hvals(items_key) or []
        parsed_items: list[dict[str, Any]] = []
        for raw in raw_items:
            try:
                parsed = json.loads(raw)
                if isinstance(parsed, dict):
                    parsed_items.append(parsed)
            except Exception:
                continue
        parsed_items.sort(key=lambda x: int(x.get("ts_ms") or 0))

        if len(parsed_items) < expected:
            return GroupAggregationResult(should_send=False, reason="awaiting_more_items")

        # Single-send guard for group completion.
        if not _redis.set(sent_key, "1", nx=True, ex=GROUP_REPORT_TTL_S):
            return GroupAggregationResult(should_send=False, reason="already_sent")

        fallback_lines = []
        for idx, item in enumerate(parsed_items, start=1):
            fallback_lines.append(f"Image {idx}: {str(item.get('item_text') or '').strip()}")
        fallback_text = "\n\n".join([line for line in fallback_lines if line.strip()]) or item_text

        compiled = _compile_group_report(
            group_id=gid,
            signal_type=signal_type,
            request_id=request_id,
            entries=parsed_items,
            fallback_text=fallback_text,
            delivery_context_prompt=delivery_context_prompt,
        )
        return GroupAggregationResult(should_send=True, compiled_text=compiled, reason="compiled")
    except Exception:
        logger.exception("group aggregation failed: group_id=%s request_id=%s", gid, request_id)
        return GroupAggregationResult(should_send=True, compiled_text=item_text, reason="aggregation_error")
